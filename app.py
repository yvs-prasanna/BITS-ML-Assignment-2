from pathlib import Path
import joblib
import pandas as pd
import streamlit as st
import matplotlib.pyplot as plt
from sklearn.metrics import accuracy_score, roc_auc_score, precision_score, recall_score, f1_score, matthews_corrcoef, confusion_matrix, classification_report

ROOT = Path(__file__).resolve().parent
MODEL_DIR = ROOT / "model"
MODEL_FILES = {
    "Logistic Regression": "logistic_regression.joblib",
    "Decision Tree": "decision_tree.joblib",
    "K-Nearest Neighbors": "k-nearest_neighbors.joblib",
    "Naive Bayes": "naive_bayes.joblib",
    "Support Vector Machine": "support_vector_machine.joblib"
}

st.set_page_config(page_title="Dry Bean Classifier", page_icon="🫘", layout="wide")
st.title("Dry Bean Variety Classification")
st.write("Compare five machine-learning classifiers using 16 numerical bean measurements.")

model_name = st.sidebar.selectbox("Choose a classification model", list(MODEL_FILES))
uploaded = st.file_uploader("Upload test_data.csv", type=["csv"])

if uploaded is None:
    default_file = ROOT / "test_data.csv"
    if not default_file.exists():
        st.warning("Run all cells in train_models.ipynb first, then upload test_data.csv.")
        st.stop()
    data = pd.read_csv(default_file)
    st.info("Using the test_data.csv generated by the training notebook.")
else:
    data = pd.read_csv(uploaded)

if "Class" not in data.columns:
    st.error("CSV must contain the actual target column named Class.")
    st.stop()

model_path = MODEL_DIR / MODEL_FILES[model_name]
if not model_path.exists():
    st.error(f"Missing {model_path.name}. Run train_models.ipynb first.")
    st.stop()

model = joblib.load(model_path)
X = data.drop(columns=["Class"])
y_true = data["Class"]
features = list(model.feature_names_in_)
missing = sorted(set(features) - set(X.columns))
if missing:
    st.error("Missing feature columns: " + ", ".join(missing))
    st.stop()
X = X[features]

try:
    predictions = model.predict(X)
    probabilities = model.predict_proba(X)
    classes = list(model.classes_)
    scores = {
        "Accuracy": accuracy_score(y_true, predictions),
        "AUC (weighted OVR)": roc_auc_score(y_true, probabilities, multi_class="ovr", average="weighted", labels=classes),
        "Precision": precision_score(y_true, predictions, average="weighted", zero_division=0),
        "Recall": recall_score(y_true, predictions, average="weighted", zero_division=0),
        "F1 Score": f1_score(y_true, predictions, average="weighted", zero_division=0),
        "MCC": matthews_corrcoef(y_true, predictions)
    }
except Exception as error:
    st.error(f"Unable to evaluate the uploaded data: {error}")
    st.stop()

st.subheader("Evaluation metrics – " + model_name)
metric_cols = st.columns(3)
for col, (label, value) in zip(metric_cols * 2, scores.items()):
    col.metric(label, f"{value:.4f}")

left, right = st.columns(2)
with left:
    st.subheader("Confusion matrix")
    matrix = confusion_matrix(y_true, predictions, labels=classes)
    fig, ax = plt.subplots(figsize=(8, 6))
    img = ax.imshow(matrix, interpolation="nearest")
    ax.set(xticks=range(len(classes)), yticks=range(len(classes)),
           xticklabels=classes, yticklabels=classes,
           xlabel="Predicted label", ylabel="True label")
    plt.setp(ax.get_xticklabels(), rotation=45, ha="right")
    fig.colorbar(img, ax=ax)
    fig.tight_layout()
    st.pyplot(fig)
    plt.close(fig)

with right:
    st.subheader("Classification report")
    report = classification_report(y_true, predictions, output_dict=True, zero_division=0)
    st.dataframe(pd.DataFrame(report).transpose().round(4), use_container_width=True)

st.subheader("Predictions")
output = data.copy()
output["Predicted_Class"] = predictions
st.dataframe(output.head(100), use_container_width=True)
st.download_button("Download predictions CSV", output.to_csv(index=False).encode("utf-8"),
                   file_name="dry_bean_predictions.csv", mime="text/csv")
